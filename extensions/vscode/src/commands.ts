export interface CommandDependencies {
  readonly state: ExtensionState;
  readonly status: SmartTestStatusBar;
  readonly results: SmartTestResultsProvider;
  readonly codeLens: SmartTestCodeLensProvider;
}

function seekDocument(arg: unknown): vscode.Uri | undefined {
  if (arg instanceof vscode.Uri) return arg;
  return undefined;
}

function stringArg(arg: unknown): string | undefined {
  return typeof arg === "string" ? arg : undefined;
}

async function resolveDocument(uri?: vscode.Uri): Promise<vscode.TextDocument | undefined> {
  if (uri) return await vscode.workspace.openTextDocument(uri);
  return vscode.window.activeTextEditor?.document;
}

function signalFromProgress(token: vscode.CancellationToken): AbortController {
  const controller = new AbortController();
  if (token.isCancellationRequested) controller.abort();
  token.onCancellationRequested(() => controller.abort());
  return controller;
}

function reportFailure(deps: CommandDependencies, context: string, error: unknown): void {
  if (isCancelledError(error)) return;
  const described = describeError(error);
  deps.state.output.appendLine(
    `[${context}] ${described.message}${described.hint ? ` (${described.hint})` : ""}`,
  );
  if (error instanceof Error && error.stack) deps.state.output.appendLine(error.stack);
  deps.state.output.show(true);
  deps.status.setError(described.message);
  void vscode.window
    .showErrorMessage(`SmartTest: ${described.message}`, "Show Output")
    .then((choice) => {
      if (choice === "Show Output") void vscode.commands.executeCommand("smarttest.openOutput");
    });
}

async function openMarkdown(content: string): Promise<void> {
  const document = await vscode.workspace.openTextDocument({ content, language: "markdown" });
  await vscode.window.showTextDocument(document, {
    viewColumn: vscode.ViewColumn.Beside,
    preview: true,
  });
  try {
    await vscode.commands.executeCommand("markdown.showPreviewToSide", document.uri);
  } catch {
    // The Markdown preview is built in; if it is unavailable the source is still open.
  }
}

function fileSummaryMarkdown(
  document: vscode.TextDocument,
  analysis: NonNullable<Awaited<ReturnType<ExtensionState["analyzeDocument"]>>>,
): string {
  const summary = summarizeFile(analysis.protections);
  const lines = [
    `# SmartTest — ${vscode.workspace.asRelativePath(document.uri, false)}`,
    "",
    `${summary.protectedUnits} protected unit(s), ${summary.unknownUnits} uncertain, ${summary.unprotectedUnits} with no static test path.`,
    "",
  ];
  if (analysis.truncated)
    lines.push(
      "> **Protection is hidden for this file** because it has more symbols than `smarttest.maxUnitsPerFile`. SmartTest does not show a partial verdict.",
      "",
    );
  if (analysis.warnings.length > 0)
    lines.push(
      `> **Unresolved code in this file:** ${analysis.warnings.join("; ")}`,
      "",
      "> Symbols below are reported as uncertain, not unprotected.",
      "",
    );
  for (const protection of analysis.protections)
    lines.push(
      `## ${protection.qualifiedName} — ${lensTitle(protection)}`,
      "",
      protection.reason,
      "",
    );
  if (analysis.protections.length === 0)
    lines.push(
      "SmartTest has no function or method units for this file. That is not a statement that it is untested.",
    );
  lines.push("", "_Generated by the SmartTest VS Code extension from local `smarttest` output._");
  return lines.join("\n");
}

/**
 * Registers the commands. The returned disposable (also added to the context)
 * aborts every run still in flight, so deactivation stops the CLI and its test
 * runners instead of leaving them behind.
 */
export function registerCommands(
  context: vscode.ExtensionContext,
  deps: CommandDependencies,
): vscode.Disposable {
  const { state, status, results, codeLens } = deps;
  /** Folders with a run in flight; a second run would race the first one's report. */
  const running = new Set<string>();
  const runControllers = new Set<AbortController>();

  const showImpact = async (...args: unknown[]): Promise<void> => {
    const uri = seekDocument(args[0]);
    const unitId = stringArg(args[1]);
    if (!state.trusted) {
      await vscode.commands.executeCommand("smarttest.showRestrictedMode");
      return;
    }
    const document = await resolveDocument(uri);
    if (!document) {
      void vscode.window.showInformationMessage("SmartTest: open a file first.");
      return;
    }
    const folder = state.folderFor(document.uri);
    if (!folder) {
      void vscode.window.showInformationMessage(
        "SmartTest: this file is not inside a workspace folder.",
      );
      return;
    }
    const controller = new AbortController();
    try {
      const analysis = await vscode.window.withProgress(
        {
          location: vscode.ProgressLocation.Window,
          title: "SmartTest: explaining protection",
        },
        async () => await state.analyzeDocument(document, controller.signal),
      );
      if (!analysis) {
        void vscode.window.showInformationMessage(
          "SmartTest could not analyse this file. See the SmartTest output.",
        );
        return;
      }
      status.setAnalysis(document.uri, analysis);
      if (unitId) {
        const protection = analysis.protections.find((p) => p.unitId === unitId);
        if (!protection) {
          void vscode.window.showInformationMessage(
            `SmartTest has no explanation for ${unitId}. Refresh the analysis and try again.`,
          );
          return;
        }
        await openMarkdown(hoverMarkdown(protection));
        return;
      }
      await openMarkdown(fileSummaryMarkdown(document, analysis));
    } catch (error) {
      reportFailure(deps, "showImpact", error);
    }
  };

  const runAffected = async (...args: unknown[]): Promise<void> => {
    const forFile = args[0] === "file";
    const uri = seekDocument(args[1]);
    if (!state.trusted) {
      await vscode.commands.executeCommand("smarttest.showRestrictedMode");
      return;
    }
    const document = await resolveDocument(uri);
    const folder = document ? state.folderFor(document.uri) : undefined;
    if (!folder) {
      void vscode.window.showInformationMessage(
        "SmartTest: open a file in a workspace folder, or run the command from a folder.",
      );
      return;
    }
    const settings = state.settingsFor(folder);
    if (settings.changeSource === "base" && !settings.baseRef.trim()) {
      const choice = await vscode.window.showErrorMessage(
        "SmartTest: `smarttest.changeSource` is `base` but `smarttest.baseRef` is empty.",
        "Open Settings",
      );
      if (choice === "Open Settings")
        await vscode.commands.executeCommand("workbench.action.openSettings", "smarttest.baseRef");
      return;
    }
    const runKey = folder.uri.toString();
    if (running.has(runKey)) {
      void vscode.window.showInformationMessage(
        "SmartTest is already running affected tests for this folder.",
      );
      return;
    }
    let resolution: ReturnType<ExtensionState["resolveFolder"]>;
    try {
      resolution = state.resolveFolder(folder);
    } catch (error) {
      reportFailure(deps, "runAffected/resolve", error);
      return;
    }

    running.add(runKey);
    status.setBusy(forFile ? "running affected tests for this file" : "running affected tests");
    status.setError(undefined);
    try {
      await vscode.window.withProgress(
        {
          location: vscode.ProgressLocation.Notification,
          title: forFile
            ? "SmartTest: running tests affected by this change set"
            : "SmartTest: running affected tests",
          cancellable: true,
        },
        async (progress, token) => {
          const controller = signalFromProgress(token);
          runControllers.add(controller);
          try {
            // Impact first: an empty selection must not record a (passing) run, which would also
            // advance a native snapshot baseline.
            progress.report({ message: "analysing the change set" });
            const impactResult = await runCli({
              ...launchOptions(resolution.launcher, impactArgs(settings)),
              cwd: folder.uri.fsPath,
              signal: controller.signal,
              timeoutMs: settings.analysisTimeoutMs,
            });
            const impact = parseImpactJson(impactResult.stdout);
            if (impact.decision.selectedTests.length === 0) {
              status.setBusy(undefined);
              status.setRun(undefined);
              void vscode.window.showInformationMessage(
                `SmartTest selected no tests for ${impact.description}. Nothing was run; this is not a pass.`,
              );
              return;
            }

            let reach: FileReach | undefined;
            if (forFile && document) {
              const projectPath = toProjectPath(folder.uri.fsPath, document.uri.fsPath);
              if (!projectPath) throw new Error("The active file is outside its workspace folder.");
              try {
                const explanation = await runCli({
                  ...launchOptions(resolution.launcher, explainArgs(explainTarget(projectPath))),
                  cwd: folder.uri.fsPath,
                  signal: controller.signal,
                  timeoutMs: settings.analysisTimeoutMs,
                });
                reach = fileReach(parseExplainJson(explanation.stdout));
              } catch (error) {
                if (isCancelledError(error)) throw error;
                const message = error instanceof Error ? error.message : String(error);
                state.output.appendLine(`[runAffected/explain] ${message}`);
                // A failed explain is "could not determine", never "no test reaches it".
                reach = { known: false, reason: message };
              }
            }

            progress.report({ message: "running selected tests" });
            const runResult = await runCli({
              ...launchOptions(resolution.launcher, runAffectedArgs(settings)),
              cwd: folder.uri.fsPath,
              signal: controller.signal,
              timeoutMs: settings.runTimeoutMs,
            });
            // Exit 4 (infrastructure) and 70 (integrity) still carry a report.
            if (runResult.exitCode !== 0 && runResult.exitCode !== 1)
              state.output.appendLine(
                `[runAffected] smarttest run exited with code ${runResult.exitCode}${
                  runResult.stderr.trim() ? `: ${runResult.stderr.trim()}` : ""
                }`,
              );
            const report = parseRunJson(runResult.stdout);
            results.setReport(report, folder.uri.fsPath, runResult.exitCode);
            status.setBusy(undefined);
            status.setRun(report.report, folder.uri.toString(), {
              integrityIssues: report.integrityIssues,
              exitCode: runResult.exitCode,
            });
            announceRun(report, runResult.exitCode, reach);
          } finally {
            runControllers.delete(controller);
          }
        },
      );
    } catch (error) {
      status.setBusy(undefined);
      if (error instanceof CancelledError || isCancelledError(error)) {
        status.setRun(undefined);
        void vscode.window.showInformationMessage(
          "SmartTest run cancelled. No result is reported as passed.",
        );
        return;
      }
      reportFailure(deps, "runAffected", error);
    } finally {
      running.delete(runKey);
    }
  };

  const explainCurrentSymbol = async (): Promise<void> => {
    if (!state.trusted) {
      await vscode.commands.executeCommand("smarttest.showRestrictedMode");
      return;
    }
    const document = vscode.window.activeTextEditor?.document;
    if (!document) {
      void vscode.window.showInformationMessage("SmartTest: open a file first.");
      return;
    }
    const controller = new AbortController();
    try {
      const [symbols, analysis] = await Promise.all([
        documentSymbols(document),
        state.analyzeDocument(document, controller.signal),
      ]);
      if (!analysis) {
        void vscode.window.showInformationMessage("SmartTest has no analysis for this file.");
        return;
      }
      if (analysis.truncated) {
        await showImpact(document.uri);
        return;
      }
      const position = vscode.window.activeTextEditor?.selection.active;
      if (!position) return;
      const binding = bindingAtPosition(
        matchUnitsToSymbols(analysis.units, symbols),
        position.line,
        position.character,
      );
      if (!binding) {
        void vscode.window.showInformationMessage(
          "SmartTest: no function or method at the cursor has a graph unit.",
        );
        return;
      }
      await showImpact(document.uri, binding.unit.id);
    } catch (error) {
      reportFailure(deps, "explainCurrentSymbol", error);
    }
  };

  const refresh = async (): Promise<void> => {
    state.invalidateAll();
    codeLens.refresh();
    status.setError(undefined);
    status.setRun(undefined);
    status.clearAnalysis();
    const document = vscode.window.activeTextEditor?.document;
    if (state.trusted && document) {
      const controller = new AbortController();
      status.setBusy("refreshing analysis");
      try {
        const analysis = await state.analyzeDocument(document, controller.signal);
        status.setBusy(undefined);
        if (analysis) status.setAnalysis(document.uri, analysis);
      } catch (error) {
        status.setBusy(undefined);
        // A failed or superseded refresh is not "refreshed".
        if (!isCancelledError(error)) reportFailure(deps, "refresh", error);
        return;
      }
    }
    void vscode.window.showInformationMessage("SmartTest analysis refreshed.");
  };

  const openOutput = (): void => {
    state.output.show(true);
  };

  const showRestrictedMode = async (): Promise<void> => {
    const choice = await vscode.window.showInformationMessage(
      "SmartTest is disabled in Restricted Mode: it runs a local executable against workspace files, so it cannot claim anything until you trust this workspace.",
      "Manage Workspace Trust",
    );
    if (choice === "Manage Workspace Trust")
      await vscode.commands.executeCommand("workbench.trust.manage");
  };

  const abortRuns: vscode.Disposable = {
    dispose: () => {
      for (const controller of runControllers) controller.abort();
      runControllers.clear();
    },
  };
  context.subscriptions.push(
    abortRuns,
    vscode.commands.registerCommand("smarttest.showImpact", showImpact),
    vscode.commands.registerCommand("smarttest.runAffected", () => runAffected()),
    vscode.commands.registerCommand("smarttest.runAffectedForFile", (uri?: unknown) =>
      runAffected("file", uri),
    ),
    vscode.commands.registerCommand("smarttest.explainCurrentSymbol", explainCurrentSymbol),
    vscode.commands.registerCommand("smarttest.refresh", refresh),
    vscode.commands.registerCommand("smarttest.openOutput", openOutput),
    vscode.commands.registerCommand("smarttest.showRestrictedMode", showRestrictedMode),
  );
  return abortRuns;
}

function announceRun(result: RunResult, exitCode: number, reach: FileReach | undefined): void {
  const report = result.report;
  const outcome = verdict(report, { integrityIssues: result.integrityIssues, exitCode });
  const detail =
    reach === undefined
      ? `${report.decision.selectedTests.length} test(s) selected.`
      : fileRunDetail(reach, report);
  const message = `SmartTest: ${outcome.headline}. ${detail}${
    outcome.details.length > 0 ? ` ${outcome.details.join(" ")}` : ""
  }`;
  const openResults = "Show Results";
  const then = (choice: string | undefined): void => {
    if (choice === openResults) void vscode.commands.executeCommand("smarttest.results.focus");
  };
  if (outcome.state === "failed")
    void vscode.window.showErrorMessage(message, openResults).then(then);
  else if (outcome.state === "passed")
    void vscode.window.showInformationMessage(message, openResults).then(then);
  else void vscode.window.showWarningMessage(message, openResults).then(then);
}
